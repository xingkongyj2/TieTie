  function easing(x) {
    let lo = 0, hi = 1
    for (let i = 0; i < 18; i++) {
      const t = (lo + hi) / 2
      const bx = 3 * (1 - t) ** 2 * t * .45 + 3 * (1 - t) * t ** 2 * .55 + t ** 3
      if (bx < x) lo = t
      else hi = t
    }
    const t = (lo + hi) / 2
    return 3 * (1 - t) * t ** 2 + t ** 3
  }
  function sample(frames, p) {
    const index = frames.findIndex(f => f[0] >= p)
    if (index <= 0) return frames[0]
    const a = frames[index - 1], b = frames[index]
    const t = easing((p - a[0]) / (b[0] - a[0]))
    return a.map((v, i) => i === 0 ? p : v + (b[i] - v) * t)
  }
